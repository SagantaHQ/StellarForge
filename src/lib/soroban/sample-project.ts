export const SAMPLE_UI_APP = `import { useEffect, useState } from "react";
import { deploy, invoke } from "@openzeppelin/adapter-stellar";

/**
 * UI for the Hello World contract.
 * Auto-generated by Soroban.Build from the contract spec.
 */
export default function HelloWorldUI({ contractId }: { contractId: string }) {
  const [greeting, setGreeting] = useState("");
  const [name, setName] = useState("");
  const [output, setOutput] = useState("");

  useEffect(() => {
    invoke(contractId, "get_greeting").then(setGreeting).catch(console.error);
  }, [contractId]);

  async function handleGreet() {
    const result = await invoke(contractId, "greet", [name]);
    setOutput(result);
  }

  return (
    <main>
      <h1>Hello World</h1>
      <p>Current greeting: {greeting}</p>
      <input value={name} onChange={(e) => setName(e.target.value)} />
      <button onClick={handleGreet}>Greet</button>
      {output && <p>Result: {output}</p>}
    </main>
  );
}
`;

