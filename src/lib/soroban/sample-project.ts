export interface FileNode {
  type: "file";
  name: string;
  path: string;
  content: string;
  language: string;
  gitStatus?: "modified" | "added" | "untracked" | null;
}

export interface FolderNode {
  type: "folder";
  name: string;
  path: string;
  children: TreeNode[];
  expanded?: boolean;
}

export type TreeNode = FileNode | FolderNode;

export const SAMPLE_CONTRACT_RUST = `#![no_std]

use soroban_sdk::{contract, contractimpl, vec, Env, String, Vec};

/// A simple Hello World contract.
/// Stores the last greeting and lets you read it back.
#[contract]
pub struct HelloWorld;

#[contractimpl]
impl HelloWorld {
    /// Initialize the contract with a default greeting.
    pub fn __constructor(env: Env) {
        let default_greeting = String::from_str(&env, "Hello");
        env.storage().instance().set(&GREETING_KEY, &default_greeting);
    }

    /// Set a new greeting. Returns the new greeting.
    pub fn set_greeting(env: Env, greeting: String) -> String {
        env.storage().instance().set(&GREETING_KEY, &greeting);
        greeting
    }

    /// Read the current greeting.
    pub fn get_greeting(env: Env) -> String {
        env.storage()
            .instance()
            .get(&GREETING_KEY)
            .unwrap_or_else(|| String::from_str(&env, "Hello"))
    }

    /// Returns a personalized greeting addressed to \`name\`.
    pub fn greet(env: Env, name: String) -> String {
        let greeting = Self::get_greeting(env.clone());
        if name.is_empty() {
            return greeting;
        }
        let mut parts: Vec<String> = vec![
            &env,
            greeting,
            String::from_str(&env, ", "),
            name,
            String::from_str(&env, "!"),
        ];
        parts.concat(&env)
    }
}

const GREETING_KEY: &str = "Greeting";
`;

